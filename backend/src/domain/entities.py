"""Domain entities for the ETF trading system.

Each entity is a plain dataclass-like object (using Pydantic for validation)
representing core business concepts.
"""

from dataclasses import dataclass, field
from datetime import datetime, date
from typing import Optional
from src.domain.enums import *


@dataclass
class ETF:
    """ETF entity representing a fund in the pool."""
    code: str
    name: str
    exchange: str                         # SH / SZ
    etf_type: str                         # A股 / 跨境
    track_index: Optional[str] = None
    theme: Optional[str] = None
    list_date: Optional[str] = None
    avg_amount_20d: float = 0.0          # 近20日日均成交额（万元）
    total_market_cap: float = 0.0         # 总市值（亿元）
    status: str = "active"
    data_status: str = "normal"
    synced_date: Optional[str] = None


@dataclass
class DailyKline:
    """Daily candlestick data."""
    etf_code: str
    trade_date: str
    open: float
    high: float
    low: float
    close: float
    volume: float                         # 成交量（手）
    amount: float                         # 成交额（万元）


@dataclass
class FactorScore:
    """Individual factor score for an ETF."""
    factor_name: str
    raw_value: float                      # 原始计算值
    z_score: float                        # Z-Score标准化得分
    weight: float                         # 权重


@dataclass
class ScreeningResult:
    """Complete screening result for a single ETF through four layers."""
    etf_code: str
    etf_name: str
    select_date: str
    # Layer 1: Basic filter
    layer1_passed: bool = False
    # Layer 2: Multi-factor scoring
    layer2_score: float = 0.0
    layer2_rank: int = 0
    factor_scores: list = field(default_factory=list)  # list[FactorScore]
    # Layer 3: Theme clustering
    layer3_theme: Optional[str] = None
    layer3_theme_rank: int = 0
    layer3_passed: bool = False
    # Layer 4: Risk filter
    layer4_death_cross: bool = False      # True = detected (bad)
    layer4_vol_price_div: bool = False
    layer4_adx_danger: bool = False
    layer4_bb_risk: bool = False
    layer4_passed: bool = False
    # Final
    final_recommended: bool = False


@dataclass
class BuySignal:
    """Buy signal generated when three conditions are met."""
    signal_id: str
    etf_code: str
    etf_name: str
    trigger_time: str
    price: float
    change_pct: float                     # 当日涨跌幅
    suggested_amount: float               # 建议买入金额
    trigger_details: dict                # 三大条件说明
    factor_summary: dict                 # 因子摘要
    status: str = "pending"


@dataclass
class SellSignal:
    """Sell signal generated by one of the 7 sell strategies."""
    signal_id: str
    etf_code: str
    etf_name: str
    trigger_time: str
    strategy_type: str                    # 策略名称
    priority: int                         # 优先级 100-65
    price: float
    buy_price: float
    pnl_amount: float
    pnl_pct: float
    action: str                           # 清仓/减仓比例
    hold_days: int
    status: str = "pending"


@dataclass
class Position:
    """Holding position for an ETF."""
    id: Optional[int] = None
    etf_code: str = ""
    etf_name: str = ""
    buy_signal_id: Optional[str] = None
    buy_date: str = ""
    buy_price: float = 0.0
    buy_amount: float = 0.0               # 买入金额
    buy_shares: float = 0.0               # 买入份额
    current_price: float = 0.0
    current_value: float = 0.0
    pnl_amount: float = 0.0
    pnl_pct: float = 0.0
    hold_days: int = 0
    is_trend_stock: bool = False
    status: str = "holding"
    sell_date: Optional[str] = None
    sell_price: Optional[float] = None
    sell_pnl_amount: Optional[float] = None
    sell_pnl_pct: Optional[float] = None
    sell_strategy: Optional[str] = None
